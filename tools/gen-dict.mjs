// Generates bend/lib/dict.bend from dictionary.json: one Phrase constructor
// per word, one Lang constructor per language, and `get` with useDict's
// English fallback worked out here.   bun tools/gen-dict.mjs
import fs from "node:fs";

const dict = JSON.parse(fs.readFileSync(new URL("../dictionary.json", import.meta.url), "utf8"));
const langs = [];
for (const w of Object.values(dict)) for (const l of Object.keys(w)) if (!langs.includes(l)) langs.push(l);
const cap = (s) => s[0].toUpperCase() + s.slice(1);
const word = (k) => "W" + cap(k);
const lang = (l) => "L" + cap(l);
const lit = (s) => JSON.stringify(s);

let out = `# Dictionary: every translated word in FreshWDL, from dictionary.json.
# Generated by tools/gen-dict.mjs; edit dictionary.json, not this file.
import Base

type Lang is Data:
${langs.map((l) => `  ${lang(l)}{}`).join("\n")}
  LOther{}

type Phrase is Data:
${Object.keys(dict).map((k) => `  ${word(k)}{}`).join("\n")}

# The config's lang code. A code the dictionary lacks reads every word in
# English, as useDict does.
def lang(+code: String) -> Lang:
${langs.map((l) => `  Bool.pick(Lang, String.eq(code, ${lit(l)}), ${lang(l)}{},`).join("\n")}
  LOther{}${")".repeat(langs.length)}

# useDict(word): the word in the language, or in English when it has none.
def get(+w: Phrase, +l: Lang) -> String:
  match w:
`;
for (const [k, tr] of Object.entries(dict)) {
  out += `    case ${word(k)}{}:\n      match l:\n`;
  for (const l of langs) {
    if (l === "en" || tr[l] === undefined) continue;
    out += `        case ${lang(l)}{}:\n          ${lit(tr[l])}\n`;
  }
  out += `        case _:\n          ${lit(tr.en ?? " ")}\n`;
}
fs.writeFileSync(new URL("../bend/lib/dict.bend", import.meta.url), out);
console.log(Object.keys(dict).length, "words,", langs.length, "languages");
