// Generates bend/wiring.bend: the plumbing between the app and the canvas
// widgets that share the standard interface (init, tip, data, resize, width,
// height, view; see bend/widgets/apparent.bend). One row per widget, in
// initAll's order, which is also the order their resize listeners run.
//   bun tools/gen-wiring.mjs
import fs from "node:fs";

// slot, module alias, module file, canvas id, widgetList key, data events
// ("cr", "cre", "both", or "" for none), init call, tip call. The tip call
// may read the slot's state as `st`; a row whose tip follows its state
// gets its tooltip refreshed after each data event (retip).
const row = (slot, A, file, id, key, ev, init, tip, retip = false) =>
  ({slot, A, file, id, key, ev, init: init ?? `${A}.init(e)`, tip: tip ?? `${A}.tip(e)`, retip});
const widgets = [
  row("apparent", "Apparent", "apparent", "Apparent01", "apparent", "cr"),
  row("temp1", "TempBar", "tempbar", "TempBar01", "temperature", "cr", "TempBar.init(TempBar.V01{}, e)", "TempBar.tip(st, e)"),
  row("temp2", "TempBar", "tempbar", "TempBar02", "temperature02", "both", "TempBar.init(TempBar.V02{}, e)", "TempBar.tip(st, e)"),
  row("temp3", "TempBar", "tempbar", "TempBar03", "temperature03", "both", "TempBar.init(TempBar.V03{}, e)", "TempBar.tip(st, e)"),
  row("barometer", "Barometer", "barometer", "Barometer01", "barometer", "cr"),
  row("windchill", "TempBar", "tempbar", "Windchill01", "windChill", "cr", "TempBar.init(TempBar.VWC{}, e)", "TempBar.tip(st, e)", true),
  row("humidity", "Humidity", "humidity", "HumidityGauge01", "humidity", "cr"),
  row("moonsun", "MoonSun", "moonsun", "MoonSun01", "moonSun", "cre", null, ""),
  row("solar", "Solar", "solar", "SolarBar01", "solar", "both"),
  row("status", "Status", "status", "Status01", "status", "", "Status.init(e, now)"),
  row("raintitle", "RainTitle", "raintitle", "TitleRainfall01", "rainfallTitle", "", null, ""),
  row("rain1", "RainBar", "rainbar", "RainBar1", "rainfallDay", "cr", "RainBar.init(RainBar.RDay{})", ""),
  row("rain2", "RainBar", "rainbar", "RainBar2", "rainfallMonth", "cr", "RainBar.init(RainBar.RMonth{})", ""),
  row("rain3", "RainBar", "rainbar", "RainBar3", "rainfallYear", "cr", "RainBar.init(RainBar.RYear{})", ""),
  row("uv", "UV", "uv", "UVBar01", "UV", "cr"),
  row("winddir", "WindDir", "winddir", "WindGauge01", "windDirection", "cr"),
  row("windspeed", "WindSpeed", "windspeed", "WindSpeed01", "windSpeed", "cr"),
];
// Slots that are not canvas widgets: carried along, set through their own defs.
const extras = [
  {slot: "graphs", A: "G", file: "graphs", init: "G.init(e)", extra: true},
  {slot: "forecast", A: "F", file: "forecast", init: "F.init(e)", extra: true},
  {slot: "records", A: "R", file: "records", init: "R.init(e)", extra: true},
];
const all = [...widgets, ...extras];
const mods = [...new Map(all.map((w) => [w.A, w.file])).entries()];

const v = (w) => w.slot;
const pats = () => all.map((w) => "+" + w.slot).join(", ");
const cat = (parts) => parts.reduceRight((acc, p) => `cat(${p}, ${acc})`, "[]");
const on = (w) => `E.on(e, "${w.key}.enabled")`;
const tipOf = (w, st) => w.tip.replaceAll("(st,", `(${st},`);

let out = `# Wiring: the canvas widgets, side by side. Generated by tools/gen-wiring.mjs
# from its table of widgets; edit the table, not this file.
import Base
import ./lib/env.bend as E
import ./lib/scene.bend as S
import ./lib/cmd.bend as C
${mods.map(([A, file]) => `import ./widgets/${file}.bend as ${A}`).join("\n")}

type Widgets is Data:
  Widgets{${all.map((w) => `${w.slot}: ${w.A}.St`).join(", ")}}

def cat(+xs: List<&2, C.Cmd>, +ys: List<&2, C.Cmd>) -> List<&2, C.Cmd>:
  List.append(&2, C.Cmd, xs, ys)

# setUp*: every widget's starting state. now: when the page loaded.
def init(+e: E.Env, +now: U32) -> Widgets:
  Widgets{${all.map((w) => w.init).join(", ")}}

# A widget's start: its tooltip when tooltips are on, or hiding its canvas
# when it is disabled.
def start.one(+on: Bool, +tips: Bool, +canvas: String, +tip: String) -> List<&2, C.Cmd>:
  match on:
    case True{}:
      Bool.pick(List<&2, C.Cmd>, tips, [C.CTip{canvas, tip}], [])
    case False{}:
      [C.CStyle{canvas, "display", "none"}]

def start(+w: Widgets, +e: E.Env) -> List<&2, C.Cmd>:
  match w:
    case Widgets{${pats()}}:
      +tips = E.on(e, "general.tooltipsEnabled")
      ${cat(widgets.map((w) => `start.one(${on(w)}, ${w.tip === "" ? "False{}" : "tips"}, "${w.id}", ${w.tip === "" ? '""' : tipOf(w, w.slot)})`))}

def canvas.one(+on: Bool, +id: String) -> List<&2, String>:
  Bool.pick(List<&2, String>, on, [id], [])

# The enabled canvases, in the order their resize listeners run.
# after_wc: what listens after Windchill01 (the forecast div, the small
# graphs); after_ms: after MoonSun01 (the records modal); modal: the graph
# modal, which listens last.
def canvases(+e: E.Env, +after_wc: List<&2, String>, +after_ms: List<&2, String>, +modal: List<&2, String>) -> List<&2, String>:
  ${widgets.reduceRight((acc, w) => `List.append(&2, String, canvas.one(${on(w)}, "${w.id}"), ${w.slot === "windchill" ? `List.append(&2, String, after_wc, ${acc})` : w.slot === "moonsun" ? `List.append(&2, String, after_ms, ${acc})` : acc})`, "modal")}
`;

for (const w of widgets) {
  const {A, id, slot: x} = w;
  out += `
def resize.${x}(+hit: Bool, +st: ${A}.St, +b: E.Box) -> ${A}.St:
  match hit:
    case True{}:
      ${A}.resize(st, b)
    case False{}:
      st

def size.${x}(+hit: Bool, +st: ${A}.St) -> List<&2, C.Cmd>:
  match hit:
    case True{}:
      [C.CSize{"${id}", ${A}.width(st), ${A}.height(st)}]
    case False{}:
      []

def draw.${x}(+on: Bool, +st: ${A}.St, +e: E.Env, +now: U32) -> List<&2, C.Cmd>:
  match on:
    case True{}:
      [C.CDraw{"${id}", ${A}.view(st, e, now)}]
    case False{}:
      []
`;
  if (w.ev !== "") out += `
def data.${x}(+go: Bool, +st: ${A}.St, +e: E.Env, +force: Bool, +now: U32) -> ${A}.St:
  match go:
    case True{}:
      ${A}.data(st, e, force, now)
    case False{}:
      st
`;
}

const evOf = (w) => ({cr: "cr", cre: "cre", both: "(cr || cre)"})[w.ev];
out += `
# A canvas's resize: the widget whose canvas it is sizes itself.
def resize(+w: Widgets, +id: String, +b: E.Box) -> Widgets:
  match w:
    case Widgets{${pats()}}:
      Widgets{${all.map((w) => w.extra ? w.slot : `resize.${w.slot}(String.eq(id, "${w.id}"), ${w.slot}, b)`).join(", ")}}

def size(+w: Widgets, +id: String) -> List<&2, C.Cmd>:
  match w:
    case Widgets{${pats()}}:
      ${cat(widgets.map((w) => `size.${w.slot}(String.eq(id, "${w.id}"), ${w.slot})`))}

# frameUpdate: every enabled stage draws.
def frame(+w: Widgets, +e: E.Env, +now: U32) -> List<&2, C.Cmd>:
  match w:
    case Widgets{${pats()}}:
      ${cat(widgets.map((w) => `draw.${w.slot}(${on(w)}, ${w.slot}, e, now)`))}

# clientRawDataUpdate (cr) and clientRawExtraDataUpdate (cre): the enabled
# widgets listening redraw. A widget on both events redraws once per event,
# which comes to the same as once.
def data(+w: Widgets, +e: E.Env, +cr: Bool, +cre: Bool, +now: U32) -> Widgets:
  match w:
    case Widgets{${pats()}}:
      Widgets{${all.map((w) => w.extra || w.ev === "" ? w.slot : `data.${w.slot}(${on(w)} && ${evOf(w)}, ${w.slot}, e, False{}, now)`).join(", ")}}

# The tooltips that follow their widget's state, after a data event.
def retip(+w: Widgets, +e: E.Env) -> List<&2, C.Cmd>:
  match w:
    case Widgets{${pats()}}:
      +tips = E.on(e, "general.tooltipsEnabled")
      ${cat(widgets.filter((w) => w.retip).map((w) => `Bool.pick(List<&2, C.Cmd>, tips && ${on(w)}, [C.CTip{"${w.id}", ${tipOf(w, w.slot)}}], [])`))}

# drawStatusS01, on every completed tryUpdateWidgets pass.
def status(+w: Widgets, +e: E.Env, +failed: List<&2, Bool>, +no_change: Bool, +now: U32) -> Widgets:
  match w:
    case Widgets{${pats()}}:
      Widgets{${all.map((w) => w.slot === "status" ? "Status.data(status, e, failed, no_change, now)" : w.slot).join(", ")}}
`;

// updateUnits: per unit kind, the widgets it redraws with unitChange true.
const units = {
  Pressure: ["barometer"],
  Wind: ["windspeed"],
  Rainfall: ["rain1", "rain2", "rain3"],
  Temp: ["temp1", "temp2", "temp3", "windchill", "apparent"],
};
out += `
# updateUnits(kind): the widgets showing that kind redraw, unitChange true.
def units(+w: Widgets, +e: E.Env, +k: String, +now: U32) -> Widgets:
  match w:
    case Widgets{${pats()}}:
      Widgets{${all.map((w) => {
        if (w.extra) return w.slot;
        const ks = Object.keys(units).filter((k) => units[k].includes(w.slot));
        return ks.length === 0 ? w.slot : `data.${w.slot}(${on(w)} && String.eq(k, "${ks[0]}"), ${w.slot}, e, True{}, now)`;
      }).join(", ")}}
`;
for (const x of extras) {
  out += `
def ${x.slot}_of(+w: Widgets) -> ${x.A}.St:
  match w:
    case Widgets{${pats()}}:
      ${x.slot}

def with_${x.slot}(+w: Widgets, +v: ${x.A}.St) -> Widgets:
  match w:
    case Widgets{${all.map((a) => "+" + (a.slot === x.slot ? "_" : a.slot)).join(", ").replace("+_", "_")}}:
      Widgets{${all.map((a) => a.slot === x.slot ? "v" : a.slot).join(", ")}}
`;
}
fs.writeFileSync(new URL("../bend/wiring.bend", import.meta.url), out);
console.log(widgets.length, "widgets wired");
